using System;
using System.Collections.Generic;
using System.Data; // מאפשר שימוש באובייקט DataTable לשליפת נתונים מרוכזת
using System.Linq;
using System.Web;
using System.Web.UI;
using System.Web.UI.WebControls;

public partial class login : System.Web.UI.Page
{
    // משתנה מחרוזת גלובלי שישמש להצגת הודעת שגיאה ב-HTML אם הפרטים לא נכונים
    public string stResult = "";

    protected void Page_Load(object sender, EventArgs e)
    {
        // =======================================================================
        //  הגנת דף - חסימת גישה למשתמשים שכבר מחוברים
        // =======================================================================
        // בדיקה: אם המשתמש כבר מחובר (כמשתמש רגיל או כמנהל) והוא מנסה להקליד את כתובת הלוגין ב-URL
        if (Session["user"] == "ok" || Session["nihul"] == "ok")
        {
            // חסימה: נעיף אותו מיד חזרה לדף הבית כי הוא לא צריך להתחבר שוב!
            Response.Redirect("about.aspx");
        }

        // =======================================================================
        // טיפול בשליחת הטופס (כאשר המשתמש לוחץ על כפתור ההתחברות)
        // =======================================================================
        // הבדיקה IsPostBack מוודאת שהקוד ירוץ רק אם הדף עבר רענון כתוצאה מלחיצה על כפתור
        if (Page.IsPostBack)
        {
            // שליפת הנתונים שהמשתמש הקליד בטופס ה-HTML באמצעות ה-name של השדות
            string gmail = Request.Form["Email"];
            string password = Request.Form["Password"];

            // -------------------------------------------------------------------
            // אפשרות 1: בדיקה האם מדובר בהתחברות של מנהל המערכת (Admin)
            // -------------------------------------------------------------------
            // קוד קשיח (Hardcoded) שמזהה את האימייל והסיסמה הייחודיים של המנהל יובל
            if (gmail == "yuvalk@gmail.com" && password == "menahel")
            {
                // יצירת משתנה Session מיוחד למנהל כדי לפתוח לו הרשאות ניהול במאסטר פייג'
                Session["nihul"] = "ok";
                // שמירת השם של המנהל לצורך הצגת הודעת ברוך הבא
                Session["name"] = "יובל המנהל";
                // הפניית המנהל באופן אוטומטי לדף הניהול המיוחד שלו
                Response.Redirect("manager.aspx");
            }
            // -------------------------------------------------------------------
            // אפשרות 2: בדיקת משתמש רגיל מול מסד הנתונים
            // -------------------------------------------------------------------
            else
            {
                // בניית שאילתת SQL מסוג SELECT כדי לחפש בטבלת tUsers משתמש עם המייל והסיסמה שהוקלדו
                // השימוש ב-N' מיועד לתמיכה מלאה בטקסט בעברית (Unicode) במידה ויש בסיסמה
                string sqlSelect =
                "SELECT * FROM tUsers " +
                "WHERE gmail = N'" + gmail + "' " +
                "AND password = N'" + password + "'";

                // הרצת השאילתה מול מסד הנתונים וקבלת התוצאה לתוך טבלת נתונים בזיכרון (DataTable)
                DataTable dt = MyAdoHelper.ExecuteDataTable(sqlSelect);

                // בדיקה: אם חזרה בדיוק שורה אחת מהמסד, זה אומר שנמצא משתמש תואם במערכת!
                if (dt.Rows.Count == 1)
                {
                    // יצירת משתנה Session למשתמש רשום כדי לעדכן את תפריט הניווט
                    Session["user"] = "ok";
                    // שליפה דינמית של השם הפרטי של המשתמש מתוך השורה שנמצאה במסד הנתונים
                    Session["name"] = dt.Rows[0]["firstname"];
                    // הפניית המשתמש המחובר בהצלחה ישירות לדף הטופס (form.aspx)
                    Response.Redirect("form.aspx");
                }
                // אם לא חזרה אף שורה (Rows.Count לא שווה ל-1), הפרטים שגויים
                else
                {
                    // עדכון הודעת השגיאה שתוצג למשתמש על המסך בתוך דף ה-HTML
                    stResult = "אימייל או סיסמה שגויים";
                }
            }
        }
    }
}